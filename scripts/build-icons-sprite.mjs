/* Build script: generates material-symbols-sprite.html.j2 from @material-symbols/svg-400 */

import { readFileSync, writeFileSync, readdirSync, watch } from 'node:fs';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const templatesDir = resolve(projectRoot, 'app/ui/templates');
const outputPath = resolve(projectRoot, 'app/ui/templates/components/common/material-symbols-sprite.html.j2');
const iconsDir = resolve(projectRoot, 'node_modules/@material-symbols/svg-400/outlined');
const watchMode = process.argv.includes('--watch');

function walkTemplates(dir) {
    const files = [];
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const fullPath = join(dir, entry.name);
        if (entry.isDirectory()) {
            files.push(...walkTemplates(fullPath));
        } else if (entry.name.endsWith('.j2')) {
            files.push(fullPath);
        }
    }
    return files;
}

function extractIconIds(files) {
    const ids = new Set();
    const pattern = /href=["']#(material-symbols-outlined-[^"'\s]+)["']/g;
    for (const file of files) {
        const content = readFileSync(file, 'utf-8');
        for (const match of content.matchAll(pattern)) {
            ids.add(match[1]);
        }
    }
    return [...ids].sort();
}

// "material-symbols-outlined-done-all" -> "done_all.svg"
function idToFileName(id) {
    return id.replace('material-symbols-outlined-', '').replace(/-/g, '_') + '.svg';
}

function parseSvg(content) {
    const viewBox = content.match(/viewBox="([^"]+)"/)?.[1];
    if (!viewBox) throw new Error('viewBox not found');
    const inner = content.match(/<svg[^>]*>([\s\S]*?)<\/svg>/)?.[1]?.trim();
    if (!inner) throw new Error('inner content not found');
    return { viewBox, inner };
}

function buildSprite() {
    const iconIds = extractIconIds(walkTemplates(templatesDir));
    console.log(`Found ${iconIds.length} Material Symbols reference(s) in templates.\n`);

    const resolved = [];
    const missing = [];

    for (const id of iconIds) {
        const fileName = idToFileName(id);
        try {
            const { viewBox, inner } = parseSvg(readFileSync(resolve(iconsDir, fileName), 'utf-8'));
            resolved.push({ id, viewBox, inner });
            console.log(`  ✓  ${id}`);
        } catch {
            missing.push({ id, fileName });
            console.error(`  ✗  ${id}  (looked for: ${fileName})`);
        }
    }

    if (missing.length > 0) {
        console.error(`\n${missing.length} icon(s) not found in @material-symbols/svg-400/outlined/.`);
        console.error('Update the template references to use valid Material Symbols names, then re-run.');
        if (!watchMode) process.exit(1);
        return;
    }

    const symbols = resolved
        .map(({ id, viewBox, inner }) =>
            `        <symbol id="${id}" viewBox="${viewBox}">\n            ${inner}\n        </symbol>`
        )
        .join('\n');

    const output =
`{#- Auto-generated by scripts/build-icons-sprite.mjs — do not edit manually -#}
{#- Run \`npm run build:icons\` to regenerate after adding new Material Symbols references to templates -#}
<svg xmlns="http://www.w3.org/2000/svg" class="hidden" aria-hidden="true" focusable="false" width="0" height="0">
    <defs>
${symbols}
    </defs>
</svg>
`;

    writeFileSync(outputPath, output, 'utf-8');
    console.log(`\nWrote ${resolved.length} symbol(s) to ${outputPath.replace(projectRoot + '/', '')}`);
}

buildSprite();

if (watchMode) {
    console.log('\nWatching templates for changes…');

    let debounceTimer;
    watch(templatesDir, { recursive: true }, (event, filename) => {
        if (!filename?.endsWith('.j2') || filename.endsWith('material-symbols-sprite.html.j2')) return;
        clearTimeout(debounceTimer);
        debounceTimer = setTimeout(() => {
            console.log(`\n[${new Date().toLocaleTimeString()}] ${filename} changed — rebuilding…\n`);
            buildSprite();
        }, 200);
    });
}
